"""Resolve and hash-lock binary wheels for the supported Docker Python target.

The resolver runs pip's cross-target wheel selection; no packages are installed.
The emitted lock is specific to CPython 3.10 on Linux x86_64 (glibc >= 2.17).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import zipfile
from email.parser import Parser
from pathlib import Path


TARGET = {
    "python_version": "3.10",
    "implementation": "cp",
    "abi": "cp310",
    "platform": "manylinux_2_17_x86_64",
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def wheel_identity(path: Path) -> tuple[str, str]:
    if path.suffix != ".whl":
        raise ValueError(f"Non-wheel artifact in binary-only resolution: {path.name}")
    with zipfile.ZipFile(path) as archive:
        metadata_names = [
            name for name in archive.namelist()
            if name.count("/") == 1 and name.endswith(".dist-info/METADATA")
        ]
        if len(metadata_names) != 1:
            raise ValueError(f"Expected one wheel METADATA file: {path.name}")
        metadata = Parser().parsestr(archive.read(metadata_names[0]).decode("utf-8"))
    name, version = metadata.get("Name"), metadata.get("Version")
    if not name or not version:
        raise ValueError(f"Wheel identity missing: {path.name}")
    return name, version


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requirements", type=Path, action="append", required=True)
    parser.add_argument("--wheel-dir", type=Path, required=True)
    parser.add_argument("--lock", type=Path, required=True)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--index-url")
    parser.add_argument("--extra-index-url", action="append", default=[])
    parser.add_argument("--find-links", action="append", default=[])
    parser.add_argument("--platform", action="append")
    parser.add_argument("--skip-download", action="store_true", help="Generate from a completed, previously resolved wheel directory")
    args = parser.parse_args()
    requirements = [path.resolve(strict=True) for path in args.requirements]
    platforms = args.platform or [TARGET["platform"]]
    target = {**TARGET, "platforms": platforms}
    args.wheel_dir.mkdir(parents=True, exist_ok=True)
    args.lock.parent.mkdir(parents=True, exist_ok=True)
    args.manifest.parent.mkdir(parents=True, exist_ok=True)

    command = [
        sys.executable, "-m", "pip", "download", "--no-cache-dir",
        "--disable-pip-version-check", "--only-binary=:all:",
        "--python-version", target["python_version"],
        "--implementation", target["implementation"],
        "--abi", target["abi"],
        "--dest", str(args.wheel_dir.resolve()),
    ]
    for platform in platforms:
        command.extend(["--platform", platform])
    if args.index_url:
        command.extend(["--index-url", args.index_url])
    for index_url in args.extra_index_url:
        command.extend(["--extra-index-url", index_url])
    for link in args.find_links:
        command.extend(["--find-links", link])
    for requirement in requirements:
        command.extend(["-r", str(requirement)])
    env = os.environ.copy()
    env["PIP_NO_INPUT"] = "1"
    if not args.skip_download:
        subprocess.run(command, check=True, env=env)

    wheels = sorted(args.wheel_dir.glob("*.whl"), key=lambda p: p.name.lower())
    if not wheels:
        raise ValueError("Resolver produced no wheels")
    entries = []
    identities = {}
    for wheel in wheels:
        name, version = wheel_identity(wheel)
        normalized = name.lower().replace("_", "-").replace(".", "-")
        if normalized in identities:
            raise ValueError(f"Multiple resolved wheels for distribution {name}")
        identities[normalized] = version
        entries.append({
            "name": name,
            "version": version,
            "filename": wheel.name,
            "sha256": sha256(wheel),
            "bytes": wheel.stat().st_size,
        })

    lines = [
        "# Generated by backend/tools/lock_docker_requirements.py.",
        f"# Target: CPython {target['python_version']}, {', '.join(platforms)} (Debian Bookworm compatible).",
        f"# Install with the index options in the manifest and --require-hashes -r {args.lock.name}.",
        "# Each hash is for the selected target wheel; this lock is platform-specific.",
    ]
    lines.extend(f"{item['name']}=={item['version']} --hash=sha256:{item['sha256']}" for item in entries)
    args.lock.write_text("\n".join(lines) + "\n", encoding="utf-8")
    manifest = {
        "status": "passed_binary_wheel_resolution_and_hash_lock",
        "target": target,
        "input_requirements": [{"path": str(path), "sha256": sha256(path)} for path in requirements],
        "indexes": {"index_url": args.index_url, "extra_index_urls": args.extra_index_url},
        "find_links": args.find_links,
        "pip_version": subprocess.check_output([sys.executable, "-m", "pip", "--version"], text=True).strip(),
        "wheel_count": len(entries),
        "wheel_bytes": sum(item["bytes"] for item in entries),
        "lock_sha256": sha256(args.lock),
        "wheels": entries,
        "scope": "Resolved Linux CPython 3.10 dependency closure from binary wheels only; no installation, image build, runtime test, or provenance certification beyond wheel content hashes.",
    }
    args.manifest.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: manifest[key] for key in ("status", "wheel_count", "wheel_bytes", "lock_sha256", "scope")}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
